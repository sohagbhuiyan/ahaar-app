import { useEffect, useRef } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { useRouter, useSegments, type Href } from 'expo-router';

import { setProfileIncompleteHandler } from '@/lib/api/client';
import { queryKeys } from '@/lib/query/keys';
import { useAuthHydrated, useIsAuthenticated } from '@/lib/store';

import { ProfileCompletionPrompt } from './ProfileCompletionPrompt';

/**
 * Keeps the route tree and the session in agreement.
 *
 * 1. A signed-in customer has no business sitting on the auth screens, so send
 *    them to Home. This is also what moves someone off login and verify-email
 *    once they succeed — those screens don't navigate themselves. Register
 *    no longer signs in (the email has to be verified first), so it moves on
 *    to verify-email itself, and nothing here gets in its way: the rule only
 *    fires once a token exists.
 *
 * 2. An incomplete profile (no name, phone or delivery address yet) is only a
 *    *suggestion* while browsing: `ProfileCompletionPrompt` offers the
 *    complete-profile screen once per app launch, and "Later" is a real
 *    choice. The hard gate is the API's — it refuses every order and
 *    subscription from such an account with 403 `profile_incomplete`, and that
 *    refusal (via `setProfileIncompleteHandler`) is what sends the customer to
 *    the complete-profile screen.
 *
 * The inverse of rule 1 — "signed out, anywhere but `(auth)` → go to login" —
 * used to live here and has been removed on purpose. The whole app is
 * browsable without an account; authentication is demanded per *action*
 * instead — see `useRequireAuth` and `LoginPrompt`.
 *
 * Nothing runs until `hasHydrated` is true: persist rehydration is async, and
 * acting on a not-yet-read session would bounce people around on cold start.
 */
export function AuthGate({ children }: { children: React.ReactNode }) {
  const router = useRouter();
  const segments = useSegments();
  const queryClient = useQueryClient();

  const hydrated = useAuthHydrated();
  const isAuthenticated = useIsAuthenticated();

  useEffect(() => {
    if (!hydrated) return;

    // Pop back to the tabs — landing on Home — rather than replacing: a
    // replace would stack a second copy of the tabs on top of the first.
    if (isAuthenticated && segments[0] === '(auth)') {
      router.dismissTo('/(tabs)');
    }
  }, [hydrated, isAuthenticated, segments, router]);

  // Read inside the handler, which outlives renders.
  const routeRef = useRef(segments[0] as string | undefined);
  useEffect(() => {
    routeRef.current = segments[0] as string | undefined;
  }, [segments]);

  // A purchase refused for an incomplete profile: re-read `/me` and send the
  // customer to finish it. Back from there returns to the purchase, which the
  // API keeps refusing until the profile is complete.
  useEffect(() => {
    setProfileIncompleteHandler(() => {
      void queryClient.invalidateQueries({ queryKey: queryKeys.profile.me() });
      if (routeRef.current !== 'complete-profile') {
        // Typed routes are regenerated by `expo start`; the cast keeps a fresh
        // checkout compiling before that has run once (as in `location/picker.ts`).
        router.push('/complete-profile' as Href);
      }
    });
    return () => setProfileIncompleteHandler(null);
  }, [queryClient, router]);

  return (
    <>
      {children}
      <ProfileCompletionPrompt />
    </>
  );
}
